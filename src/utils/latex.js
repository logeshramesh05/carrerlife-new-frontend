export function applyStarter(category, existing) {
  const starter = STAGE_STARTERS[category] || STAGE_STARTERS.EARLY_CAREER;
  return {
    ...existing,
    headline: existing.headline || starter.headline,
    summary: existing.summary || starter.summary,
    skillGroups: existing.skillGroups && Object.values(existing.skillGroups).some((v) => v?.length)
      ? existing.skillGroups
      : starter.skillGroups,
  };
}
